function summary = verify_reproduction(outDir)
%VERIFY_REPRODUCTION Recompute both studies, export certificates, compare MATs.
% Default output is reproduced_results/, preserving the reference results/.
repo=fileparts(mfilename('fullpath'));
if nargin<1||isempty(outDir),outDir=fullfile(repo,'reproduced_results');end
if ~isfolder(outDir),mkdir(outDir);end
reference1=load(fullfile(repo,'results','example1','example1_results.mat'),'results');
reference2=load(fullfile(repo,'results','example2','example2_results.mat'),'results');
oldOutput=getenv('DRNE_RESULTS_DIR');setenv('DRNE_RESULTS_DIR',outDir);
envCleanup=onCleanup(@()setenv('DRNE_RESULTS_DIR',oldOutput)); %#ok<NASGU>
logfile=fullfile(outDir,'reproduction_log.txt');fid=fopen(logfile,'w');assert(fid>=0);fclose(fid);
diary(logfile);diaryCleanup=onCleanup(@()diary('off')); %#ok<NASGU>
fprintf('Command: summary = verify_reproduction\nMATLAB %s\nPlatform %s\n',version,computer);
started=tic;
run_study(fullfile(repo,'example1_theory_verification.m'));
run_study(fullfile(repo,'example2_statistical_robustness.m'));
a=load(fullfile(outDir,'example1','example1_results.mat'),'results');
b=load(fullfile(outDir,'example2','example2_results.mat'),'results');
comparisons={compare_numeric_records(reference1.results,a.results), ...
    compare_numeric_records(reference2.results,b.results)};
write_json(fullfile(outDir,'reference_comparison.json'),comparisons);
assert(all(cellfun(@(x)x.pass,comparisons)),'Recomputed arrays differ from archived references.');
r=a.results;
record1=struct('parameters',r.parameters,'constants',r.constants,'certificate',r.certificate, ...
    'gains',r.gains,'theoryAudit',r.theoryAudit,'solverSettings',r.solverSettings, ...
    'initialization',r.initialization,'publicationAuditSummary',r.publicationAuditSummary, ...
    'xProxyNE',r.xProxyNE,'xReferenceDRNE',r.xExactDRNE, ...
    'proxyPlayerGaps',r.proxyPlayerGaps,'referencePlayerGaps',r.exactDRPlayerGaps, ...
    'proxyOriginalDRPlayerGaps',r.proxyOriginalDRPlayerGaps, ...
    'multiInitialTerminalSummary',r.multiInitialTerminalSummary, ...
    'approximationCertificate',r.approximationCertificate, ...
    'certificateToActualGapRatio',r.certificateToActualGapRatio, ...
    'certificateWouldBeInformative',r.certificateWouldBeInformative);
write_full_precision(fullfile(outDir,'example1_certificate.txt'),record1);
writetable(r.theoryAudit,fullfile(outDir,'example1_theorem_audit.csv'));
write_json(fullfile(outDir,'example1_initialization.json'),r.initialization);
r=b.results;
record2=struct('parameters',r.parameters,'Kgrid',r.Kgrid,'theoryByK',{r.theoryByK}, ...
    'gainByK',{r.gainByK},'auditByK',{r.auditByK},'solverSettings',r.solverSettings, ...
    'nCalibration',r.nCalibration,'nCoverage',r.nCoverage,'nEquilibriumRep',r.nEquilibriumRep, ...
    'nHeldout',r.nHeldout,'calibrationSeeds',r.calibrationSeeds,'coverageSeeds',r.coverageSeeds, ...
    'equilibriumDatasetSeeds',r.equilibriumDatasetSeeds,'heldoutSeeds',r.heldoutSeeds, ...
    'coverageProbability',r.coverageProbability,'coverageCI',r.coverageWilsonCI, ...
    'sampleGapMedian',r.sampleGapMedian,'populationProxyReferenceGap',r.populationProxyReferenceGap, ...
    'rhoExactGap',r.rhoExactGap,'epsExactGap',r.epsExactGap, ...
    'budgetMapExactResidual',r.budgetMapExactResidual, ...
    'fixedDualTradeoff',r.fixedDualTradeoff,'baseDatasetSeed',r.baseDatasetSeed, ...
    'scope','Monte Carlo coverage uses the known generating law; fixed-dual proxy NE is distinct from original-game DRNE.');
write_full_precision(fullfile(outDir,'example2_certificate.txt'),record2);
auditRows=table();
for k=1:numel(r.Kgrid)
    q=r.auditByK{k};q.K=repmat(r.Kgrid(k),height(q),1);auditRows=[auditRows;q]; %#ok<AGROW>
end
writetable(auditRows,fullfile(outDir,'example2_theorem_audit.csv'));
write_json(fullfile(outDir,'statistical_protocol.json'),rmfield(record2, ...
    {'parameters','theoryByK','gainByK','auditByK','rhoExactGap','epsExactGap','budgetMapExactResidual','fixedDualTradeoff'}));
summary=struct('matlabVersion',version,'release',version('-release'),'platform',computer, ...
    'optimizationToolbox',ver('optim'),'fromScratch',true,'example1Checks',height(a.results.theoryAudit), ...
    'example2Checks',height(auditRows),'example1Initializations',a.results.numberOfInitialConditions, ...
    'example2SampleSizes',r.Kgrid,'parallelWorkers',r.parallelWorkers, ...
    'referenceNumericallyIdentical',cellfun(@(x)x.numericallyIdentical,comparisons), ...
    'referenceMaxAbsoluteDifference',cellfun(@(x)x.maxAbsoluteDifference,comparisons), ...
    'referenceNumericValues',cellfun(@(x)x.numericValues,comparisons), ...
    'wallSeconds',toc(started),'status','VERIFICATION_PASS');
write_json(fullfile(outDir,'verification_summary.json'),summary);
fprintf('VERIFICATION_PASS: Example 1 %d checks; Example 2 %d checks\n',summary.example1Checks,summary.example2Checks);
end

function run_study(studyFile)
% The original scripts clear their workspace; keep that clear inside this call.
run(studyFile);
end

function write_json(path,data)
fid=fopen(path,'w');assert(fid>=0);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n',jsonencode(data,'PrettyPrint',true));
end
